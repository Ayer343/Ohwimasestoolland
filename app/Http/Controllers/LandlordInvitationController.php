    /**
     * ✅ UPDATED: Send invitation via multiple channels with token support
     */
    private function sendInvitation(LandlordInvitation $invitation): array
    {
        try {
            $landlord = $invitation->landlord;
            $property = $invitation->property;

            $availableChannels = $this->multiChannelInvitationService->getAvailableChannels($landlord);
            $channelsToUse = array_intersect($invitation->channels, $availableChannels);

            if (empty($channelsToUse)) {
                $invitation->markAsFailed('No available communication channels for this landlord.');
                return [
                    'success' => false,
                    'message' => 'No available communication channels for this landlord.'
                ];
            }

            $results = [];
            $successCount = 0;

            foreach ($channelsToUse as $channel) {
                $result = $this->multiChannelInvitationService->sendMessage(
                    $landlord,
                    $this->generateInvitationMessage($invitation),
                    'landlord_invitation',
                    [
                        'channel' => $channel,
                        'invitation_id' => $invitation->id,
                        'property_id' => $property->id,
                        'landlord_id' => $landlord->id,
                        'invitation_url' => $invitation->getInvitationUrl(),
                        'invitation_token' => $invitation->token,
                        'landlord' => $landlord,
                        'property' => $property,
                        'invitation' => $invitation
                    ]
                );

                $results[$channel] = $result;
                if ($result['success']) {
                    $successCount++;
                }
            }

            if ($successCount > 0) {
                $invitation->markAsSent($channelsToUse);
                
                Log::info('Landlord invitation sent successfully', [
                    'invitation_id' => $invitation->id,
                    'landlord_id' => $landlord->id,
                    'property_id' => $property->id,
                    'token' => $invitation->token,
                    'channels_successful' => array_keys(array_filter($results, fn($r) => $r['success'])),
                    'success_count' => $successCount
                ]);

                return [
                    'success' => true,
                    'message' => "Invitation sent via {$successCount} channel(s)",
                    'results' => $results,
                    'channels_successful' => array_keys(array_filter($results, fn($r) => $r['success'])),
                    'channels_attempted' => $channelsToUse,
                    'invitation_url' => $invitation->getInvitationUrl(),
                    'token' => $invitation->token
                ];
            } else {
                $invitation->markAsFailed('All communication channels failed');
                
                return [
                    'success' => false,
                    'message' => 'Failed to send invitation via any channel',
                    'results' => $results,
                    'channels_attempted' => $channelsToUse
                ];
            }

        } catch (\Exception $e) {
            Log::error('Failed to send landlord invitation: ' . $e->getMessage(), [
                'invitation_id' => $invitation->id,
                'token' => $invitation->token
            ]);
            $invitation->markAsFailed($e->getMessage());

            return [
                'success' => false,
                'message' => 'Failed to send invitation: ' . $e->getMessage()
            ];
        }
    }

    /**
     * Generate invitation message
     */
    private function generateInvitationMessage(LandlordInvitation $invitation): string
    {
        $landlord = $invitation->landlord;
        $property = $invitation->property;

        $message = "Hello {$landlord->name}!\n\n";

        switch ($invitation->invitation_type) {
            case LandlordInvitation::TYPE_PROPERTY_ADDED:
                $message .= "A new property has been added to your account:\n";
                break;
            case LandlordInvitation::TYPE_WELCOME:
                $message .= "Welcome to our property management system!\n";
                break;
            default: // registration
                $message .= "Your property has been registered in our system:\n";
        }

        $message .= "🏠 Property: {$property->property_name}\n";
        $message .= "📍 Location: {$property->street_name}, {$property->zone}\n";
        $message .= "🔢 Registration: {$property->registration_pattern}\n\n";

        if ($invitation->custom_message) {
            $message .= "{$invitation->custom_message}\n\n";
        }

        $message .= "To complete your registration and access your portal, please click:\n";
        $message .= "{$invitation->getInvitationUrl()}\n\n";
        $message .= "This link expires on {$invitation->expires_at->format('M j, Y')}";

        return $message;
    }

    /**
     * ✅ UPDATED: Get invitation statistics with token insights
     */
    public function statistics()
    {
        $stats = [
            'total_invitations' => LandlordInvitation::count(),
            'pending_invitations' => LandlordInvitation::pending()->count(),
            'active_invitations' => LandlordInvitation::active()->count(),
            'accepted_invitations' => LandlordInvitation::where('status', LandlordInvitation::STATUS_ACCEPTED)->count(),
            'expired_invitations' => LandlordInvitation::expired()->count(),
            'failed_invitations' => LandlordInvitation::where('status', LandlordInvitation::STATUS_FAILED)->count(),
            
            'invitations_by_type' => LandlordInvitation::groupBy('invitation_type')
                ->select('invitation_type', DB::raw('count(*) as count'))
                ->get()
                ->pluck('count', 'invitation_type'),
                
            'average_acceptance_time' => LandlordInvitation::where('status', LandlordInvitation::STATUS_ACCEPTED)
                ->whereNotNull('sent_at')
                ->whereNotNull('accepted_at')
                ->select(DB::raw('AVG(TIMESTAMPDIFF(HOUR, sent_at, accepted_at)) as avg_hours'))
                ->value('avg_hours'),
                
            // ✅ ADDED: Token-related statistics
            'invitations_with_tokens' => LandlordInvitation::whereNotNull('token')->count(),
            'unique_tokens' => LandlordInvitation::select('token')->distinct()->count(),
        ];

        return response()->json([
            'success' => true,
            'stats' => $stats,
            'message' => 'Invitation statistics retrieved successfully'
        ]);
    }

    /**
     * ✅ NEW: Regenerate token for an invitation
     */
    public function regenerateToken(LandlordInvitation $landlordInvitation)
    {
        DB::beginTransaction();

        try {
            $oldToken = $landlordInvitation->token;
            $newToken = LandlordInvitation::generateToken();
            
            $landlordInvitation->update([
                'token' => $newToken,
                'status' => LandlordInvitation::STATUS_PENDING,
                'sent_at' => null,
                'attempts' => 0
            ]);

            Log::info('Landlord invitation token regenerated', [
                'invitation_id' => $landlordInvitation->id,
                'old_token' => $oldToken,
                'new_token' => $newToken,
                'regenerated_by' => auth()->id()
            ]);

            DB::commit();

            return response()->json([
                'success' => true,
                'message' => 'Token regenerated successfully. The old invitation link is now invalid.',
                'new_invitation_url' => $landlordInvitation->getInvitationUrl(),
                'new_token' => $newToken
            ]);

        } catch (\Exception $e) {
            DB::rollBack();
            Log::error('Failed to regenerate token: ' . $e->getMessage(), [
                'invitation_id' => $landlordInvitation->id
            ]);

            return response()->json([
                'success' => false,
                'message' => 'Failed to regenerate token. Please try again.',
                'error' => $e->getMessage()
            ], 500);
        }
    }
