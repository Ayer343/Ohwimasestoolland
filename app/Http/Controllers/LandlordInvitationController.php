    /**
     * ✅ UPDATED: Store a newly created landlord invitation with token support
     * This is now primarily called from PropertyController during property registration
     */
    public function store(Request $request)
    {
        $validator = Validator::make($request->all(), [
            'property_id' => 'required|exists:properties,id',
            'landlord_id' => 'required|exists:users,id',
            'channels' => 'required|array',
            'channels.*' => 'in:email,sms,whatsapp',
            'invitation_type' => 'required|in:registration,property_added,welcome',
            'custom_message' => 'nullable|string|max:500',
            'expires_in_days' => 'nullable|integer|min:1|max:30'
        ]);

        if ($validator->fails()) {
            return response()->json([
                'success' => false,
                'message' => 'Validation failed',
                'errors' => $validator->errors()
            ], 422);
        }

        DB::beginTransaction();

        try {
            // ✅ UPDATED: Check if landlord already has an active invitation for this property
            $existingInvitation = LandlordInvitation::where('property_id', $request->property_id)
                ->where('landlord_id', $request->landlord_id)
                ->whereIn('status', [
                    LandlordInvitation::STATUS_PENDING,
                    LandlordInvitation::STATUS_SENT
                ])
                ->where('expires_at', '>', now())
                ->first();

            if ($existingInvitation) {
                return response()->json([
                    'success' => false,
                    'message' => 'This landlord already has an active invitation for this property.',
                    'existing_invitation_id' => $existingInvitation->id
                ], 409);
            }

            // ✅ FIXED: Create the invitation (token is automatically generated by model)
            $invitation = LandlordInvitation::create([
                'property_id' => $request->property_id,
                'landlord_id' => $request->landlord_id,
                'invited_by' => auth()->id(),
                'channels' => $request->channels,
                'invitation_type' => $request->invitation_type,
                'custom_message' => $request->custom_message,
                'expires_at' => now()->addDays($request->expires_in_days ?? 7)
                // Token is automatically generated by model boot method
            ]);

            // ✅ ENHANCED: Log invitation creation with token
            Log::info('Landlord invitation created', [
                'invitation_id' => $invitation->id,
                'property_id' => $request->property_id,
                'landlord_id' => $request->landlord_id,
                'token' => $invitation->token,
                'invitation_url' => $invitation->getInvitationUrl(),
                'created_by' => auth()->id()
            ]);

            // Send the invitation
            $sendResult = $this->sendInvitation($invitation);

            DB::commit();

            $responseData = [
                'success' => $sendResult['success'],
                'message' => $sendResult['success'] ? 
                    'Landlord invitation created and sent successfully!' : 
                    'Invitation created but failed to send: ' . $sendResult['message'],
                'invitation_id' => $invitation->id,
                'token' => $invitation->token,
                'invitation_url' => $invitation->getInvitationUrl(),
                'send_result' => $sendResult
            ];

            return response()->json($responseData, $sendResult['success'] ? 201 : 200);

        } catch (\Exception $e) {
            DB::rollBack();
            Log::error('Failed to create landlord invitation: ' . $e->getMessage(), [
                'property_id' => $request->property_id ?? 'unknown',
                'landlord_id' => $request->landlord_id ?? 'unknown',
                'user_id' => auth()->id()
            ]);

            return response()->json([
                'success' => false,
                'message' => 'Failed to create landlord invitation. Please try again.',
                'error' => $e->getMessage()
            ], 500);
        }
    }

    /**
     * ✅ UPDATED: Resend a landlord invitation with improved token handling
     * This is typically called from the property show page
     */
    public function resend(Request $request, LandlordInvitation $landlordInvitation)
    {
        $validator = Validator::make($request->all(), [
            'channels' => 'sometimes|array',
            'channels.*' => 'in:email,sms,whatsapp',
            'custom_message' => 'nullable|string|max:500',
            'expires_in_days' => 'nullable|integer|min:1|max:30'
        ]);

        if ($validator->fails()) {
            return response()->json([
                'success' => false,
                'message' => 'Validation failed',
                'errors' => $validator->errors()
            ], 422);
        }

        DB::beginTransaction();

        try {
            // ✅ ENHANCED: Update invitation with new data
            $updateData = [];
            
            if ($request->has('channels')) {
                $updateData['channels'] = $request->channels;
            }
            
            if ($request->has('custom_message')) {
                $updateData['custom_message'] = $request->custom_message;
            }

            if ($request->has('expires_in_days')) {
                $updateData['expires_at'] = now()->addDays($request->expires_in_days);
            }
            
            if (!empty($updateData)) {
                $landlordInvitation->update($updateData);
            }

            // ✅ FIXED: Reset to pending status for resend
            $landlordInvitation->resend($request->channels ?? []);

            // Resend the invitation
            $sendResult = $this->sendInvitation($landlordInvitation);

            DB::commit();

            // ✅ ENHANCED: Better response with invitation details
            if ($sendResult['success']) {
                Log::info('Landlord invitation resent successfully', [
                    'invitation_id' => $landlordInvitation->id,
                    'token' => $landlordInvitation->token,
                    'channels' => $sendResult['channels_successful'] ?? []
                ]);

                return response()->json([
                    'success' => true,
                    'message' => 'Landlord invitation resent successfully!',
                    'invitation_url' => $landlordInvitation->getInvitationUrl(),
                    'token' => $landlordInvitation->token,
                    'send_result' => $sendResult
                ]);
            } else {
                Log::error('Failed to resend landlord invitation', [
                    'invitation_id' => $landlordInvitation->id,
                    'token' => $landlordInvitation->token,
                    'error' => $sendResult['message']
                ]);

                return response()->json([
                    'success' => false,
                    'message' => 'Failed to resend invitation: ' . $sendResult['message'],
                    'invitation_url' => $landlordInvitation->getInvitationUrl(),
                    'token' => $landlordInvitation->token,
                    'send_result' => $sendResult
                ], 500);
            }

        } catch (\Exception $e) {
            DB::rollBack();
            Log::error('Failed to resend landlord invitation: ' . $e->getMessage(), [
                'invitation_id' => $landlordInvitation->id,
                'token' => $landlordInvitation->token
            ]);

            return response()->json([
                'success' => false,
                'message' => 'Failed to resend landlord invitation. Please try again.',
                'error' => $e->getMessage()
            ], 500);
        }
    }

