    /**
     * ✅ FIXED: Accept landlord invitation (for landlords) with token validation
     * Now includes systemSettings to fix the Blade template error
     */
    public function accept(Request $request, $token)
    {
        // ✅ FIXED: Use the model's token-based finder method
        $invitation = LandlordInvitation::findByToken($token);
        
        if (!$invitation) {
            return redirect()->route('login')
                ->with('error', 'Invalid invitation link. Please check the URL or request a new invitation.');
        }

        // Check if invitation is valid
        if ($invitation->isExpired()) {
            return redirect()->route('login')
                ->with('error', 'This invitation link has expired. Please request a new one.');
        }

        if ($invitation->status === LandlordInvitation::STATUS_CANCELLED) {
            return redirect()->route('login')
                ->with('error', 'This invitation has been cancelled.');
        }

        if ($invitation->status === LandlordInvitation::STATUS_ACCEPTED) {
            return redirect()->route('login')
                ->with('info', 'This invitation has already been accepted.');
        }

        // If landlord is already logged in, verify it's the correct user
        if (auth()->check() && auth()->id() !== $invitation->landlord_id) {
            auth()->logout();
            return redirect()->route('landlord.invitations.accept', ['token' => $token])
                ->with('error', 'Please login with the correct landlord account to accept this invitation.');
        }

        // ✅ ADDED: Get system settings to fix the Blade template error
        $systemSettings = SystemSetting::first();
        
        // ✅ ADDED: Provide default system settings if not found
        if (!$systemSettings) {
            $systemSettings = (object) [
                'system_name' => 'Property Management System',
                'system_logo' => null,
                'support_email' => 'support@example.com',
                'system_phone' => null,
                'support_email' => 'support@example.com',
            ];
        }

        // ✅ ADDED: Log invitation access
        Log::info('Landlord accessed invitation acceptance form', [
            'invitation_id' => $invitation->id,
            'token' => $invitation->token,
            'landlord_id' => $invitation->landlord_id,
            'ip_address' => $request->ip()
        ]);

        // ✅ FIXED: Show acceptance form with systemSettings variable
        return view('landlord.invitations.accept', [
            'invitation' => $invitation,
            'token' => $token,
            'systemSettings' => $systemSettings // ✅ This fixes the error
        ]);
    }

    /**
     * ✅ UPDATED: Process invitation acceptance with enhanced security
     */
    public function processAcceptance(Request $request, $token)
    {
        // ✅ FIXED: Use the model's token-based finder method
        $invitation = LandlordInvitation::findByToken($token);
        
        if (!$invitation) {
            return redirect()->route('login')
                ->with('error', 'Invalid invitation token. Please request a new invitation.');
        }

        // Validate invitation
        if (!$invitation->isActive()) {
            return redirect()->route('login')
                ->with('error', 'This invitation is no longer valid.');
        }

        $validator = Validator::make($request->all(), [
            'password' => 'required|min:8|confirmed',
            'agree_terms' => 'required|accepted',
            'phone' => 'sometimes|required|string|max:20'
        ]);

        if ($validator->fails()) {
            return redirect()->back()
                ->withErrors($validator)
                ->withInput()
                ->with('token', $token);
        }

        DB::beginTransaction();

        try {
            $landlord = $invitation->landlord;

            // ✅ FIXED: Use Hash facade for password hashing
            $updateData = [
                'password' => Hash::make($request->password),
                'is_active' => true,
                'email_verified_at' => $landlord->email_verified_at ?? now()
            ];

            if ($request->filled('phone')) {
                $updateData['phone'] = $request->phone;
            }

            $landlord->update($updateData);

            // Mark invitation as accepted
            $invitation->markAsAccepted();

            // ✅ ENHANCED: Log the acceptance with more details
            Log::info('Landlord invitation accepted successfully', [
                'invitation_id' => $invitation->id,
                'token' => $invitation->token,
                'landlord_id' => $landlord->id,
                'property_id' => $invitation->property_id,
                'accepted_at' => now()->toISOString(),
                'ip_address' => $request->ip()
            ]);

            DB::commit();

            // Auto-login the landlord
            auth()->login($landlord);

            return redirect()->route('landlord.dashboard')
                ->with('success', 'Registration completed successfully! Welcome to your landlord portal.');

        } catch (\Exception $e) {
            DB::rollBack();
            Log::error('Error processing landlord invitation acceptance: ' . $e->getMessage(), [
                'invitation_id' => $invitation->id ?? 'unknown',
                'token' => $token,
                'landlord_id' => $invitation->landlord_id ?? 'unknown'
            ]);

            return redirect()->back()
                ->with('error', 'Failed to complete registration. Please try again.')
                ->withInput()
                ->with('token', $token);
        }
    }

