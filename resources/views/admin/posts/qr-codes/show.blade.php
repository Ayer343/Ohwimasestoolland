// Handle regenerate form submission - FIXED VERSION
document.addEventListener('DOMContentLoaded', function() {
    const regenerateForm = document.getElementById('regenerateForm');
    if (regenerateForm) {
        regenerateForm.addEventListener('submit', function(e) {
            e.preventDefault();
            
            const reason = document.getElementById('regenerateReason').value;
            const formData = new FormData(this);
            
            if (reason) {
                formData.append('reason', reason);
            }
            
            showLoading('Regenerating attendance QR code...');
            
            // FIXED: Added proper headers for AJAX
            fetch(this.action, {
                method: 'POST',
                body: formData,
                headers: {
                    'X-CSRF-TOKEN': '{{ csrf_token() }}',
                    'Accept': 'application/json',
                    'X-Requested-With': 'XMLHttpRequest'
                }
            })
            .then(async response => {
                // Check if response is OK
                if (!response.ok) {
                    throw new Error(`Server error: ${response.status}`);
                }
                
                // Check content type
                const contentType = response.headers.get('content-type');
                if (contentType && contentType.includes('application/json')) {
                    return await response.json();
                } else {
                    // If not JSON, check if it's a redirect
                    const text = await response.text();
                    
                    // Check for meta refresh redirect
                    const metaMatch = text.match(/url=([^"']+)/i);
                    if (metaMatch) {
                        window.location.href = metaMatch[1];
                        return { success: true, redirect: metaMatch[1] };
                    }
                    
                    // Check for JavaScript redirect
                    if (text.includes('window.location') || text.includes('location.href')) {
                        // Page will redirect, we can just reload
                        setTimeout(() => window.location.reload(), 100);
                        return { success: true };
                    }
                    
                    throw new Error('Unexpected response format from server');
                }
            })
            .then(data => {
                hideLoading();
                closeModal('regenerateModal');
                
                if (data.success) {
                    showToast(data.message || 'QR code regenerated successfully!', 'success');
                    
                    // Handle redirect if provided
                    if (data.redirect) {
                        setTimeout(() => {
                            window.location.href = data.redirect;
                        }, 1500);
                    } else {
                        // Refresh to show updated QR code
                        setTimeout(() => {
                            window.location.reload();
                        }, 1500);
                    }
                } else {
                    showToast(data.message || 'Failed to regenerate QR code', 'error');
                }
            })
            .catch(error => {
                hideLoading();
                console.error('Regenerate Error:', error);
                showToast(error.message || 'Network error occurred', 'error');
            });
        });
    }

    // Handle delete form submission - ADDED FOR COMPLETENESS
    const deleteForm = document.getElementById('deleteForm');
    if (deleteForm) {
        deleteForm.addEventListener('submit', function(e) {
            e.preventDefault();
            
            showLoading('Deleting QR code...');
            
            fetch(this.action, {
                method: 'POST',
                body: new FormData(this),
                headers: {
                    'X-CSRF-TOKEN': '{{ csrf_token() }}',
                    'Accept': 'application/json',
                    'X-Requested-With': 'XMLHttpRequest'
                }
            })
            .then(async response => {
                if (!response.ok) {
                    throw new Error(`Server error: ${response.status}`);
                }
                
                const contentType = response.headers.get('content-type');
                if (contentType && contentType.includes('application/json')) {
                    return await response.json();
                } else {
                    // Handle redirect
                    const text = await response.text();
                    if (response.redirected || text.includes('window.location')) {
                        setTimeout(() => window.location.reload(), 100);
                        return { success: true };
                    }
                    throw new Error('Unexpected response format');
                }
            })
            .then(data => {
                hideLoading();
                closeModal('deleteModal');
                
                if (data.success) {
                    showToast(data.message || 'QR code deleted successfully', 'success');
                    setTimeout(() => {
                        window.location.href = '{{ route("admin.security-posts.qr-codes.index", $post->id) }}';
                    }, 1500);
