}

// Toggle QR Code Status
async function toggleStatus(qrId, newStatus) {
    if (!confirm(`Are you sure you want to ${newStatus ? 'activate' : 'deactivate'} this attendance QR code?`)) {
        return;
    }
    
    showLoading('Updating QR code status...');
    
    try {
        const response = await fetch(`/admin/security-posts/{{ $post->id }}/qr-codes/${qrId}/update-status`, {
            method: 'POST',
            headers: {
                'X-CSRF-TOKEN': '{{ csrf_token() }}',
                'Content-Type': 'application/json',
                'Accept': 'application/json',
                'X-Requested-With': 'XMLHttpRequest'
            },
            body: JSON.stringify({
                is_active: newStatus,
                reason: `Manual ${newStatus ? 'activation' : 'deactivation'} from details page`
            })
        });
        
        // Check if response is OK
        if (!response.ok) {
            throw new Error(`Server error: ${response.status}`);
        }
        
        // Check content type
        const contentType = response.headers.get('content-type');
        if (!contentType || !contentType.includes('application/json')) {
            throw new Error('Invalid response format from server');
        }
        
        const data = await response.json();
        hideLoading();
        
        if (data.success) {
            showToast(data.message, 'success');
            setTimeout(() => location.reload(), 1500);
        } else {
            showToast(data.message || 'Failed to update status', 'error');
        }
    } catch (error) {
        hideLoading();
        console.error('Toggle Status Error:', error);
        showToast(error.message || 'Network error occurred', 'error');
    }
}

